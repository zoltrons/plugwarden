// Forwarder request shaping: the URLs, auth headers and bodies the official clients send, and the
// fields they read back. Ported from clients libs/tools/generator/core/src/integration/*.spec.ts.
import assert from "node:assert/strict";
import { test } from "node:test";
import {
  ALIAS_INFO,
  AliasError,
  aliasAccountId,
  aliasGeneratedBy,
  aliasAccountRequest,
  aliasBaseUrl,
  aliasCreateRequest,
  aliasHost,
  aliasResult,
  defaultAliasSettings,
  missingAliasFields,
  normalizeAliasBaseUrl,
  websitePrefix,
  type AliasContext,
  type AliasSettings,
} from "./alias.ts";

const settings = (patch: Partial<AliasSettings>): AliasSettings => ({ ...defaultAliasSettings("simplelogin"), ...patch });
const website = "https://shop.example.com/checkout?x=1";
const generatedBy = (target: string) => (target ? `Website: ${target}. Generated by Plugwarden.` : "Generated by Plugwarden.");
const ctx: AliasContext = { website, generatedBy };

const body = (req: { body?: string }) => JSON.parse(req.body ?? "null") as Record<string, unknown>;

test("alias: the base URL is the public API unless a self-hosted one is set", () => {
  assert.equal(aliasBaseUrl(settings({ vendor: "simplelogin" })), "https://app.simplelogin.io");
  assert.equal(aliasBaseUrl(settings({ vendor: "simplelogin", baseUrl: "https://sl.example.net/" })), "https://sl.example.net");
  // Only services that allow self-hosting read the field (upstream `selfHost: "maybe"`).
  assert.equal(aliasBaseUrl(settings({ vendor: "duckduckgo", baseUrl: "https://evil.example" })), "https://quack.duckduckgo.com/api");
  assert.equal(aliasBaseUrl(settings({ vendor: "fastmail", baseUrl: "https://evil.example" })), "https://api.fastmail.com");
});

test("alias: an API URL must be https, except on loopback", () => {
  assert.equal(normalizeAliasBaseUrl("localhost:8080/base/"), "https://localhost:8080/base");
  assert.equal(normalizeAliasBaseUrl("http://127.0.0.1:3000"), "http://127.0.0.1:3000");
  assert.throws(() => normalizeAliasBaseUrl("http://sl.example.net"), AliasError);
  assert.throws(() => normalizeAliasBaseUrl("https://user:pw@sl.example.net"), AliasError);
  assert.throws(() => normalizeAliasBaseUrl("https://sl.example.net/?x=1"), AliasError);
  assert.throws(() => normalizeAliasBaseUrl("https://"), AliasError);
});

test("alias: required settings per service", () => {
  assert.deepEqual(missingAliasFields(settings({ vendor: "simplelogin" })), ["token"]);
  assert.deepEqual(missingAliasFields(settings({ vendor: "addyio" })), ["token", "domain"]);
  assert.deepEqual(missingAliasFields(settings({ vendor: "simplelogin", token: "t" })), []);
  assert.deepEqual(missingAliasFields(settings({ vendor: "addyio", token: "t", domain: "example.com" })), []);
  assert.deepEqual(missingAliasFields(settings({ vendor: "forwardemail", token: "t" })), ["domain"]);
});

test("alias: the website host and Fastmail's website prefix", () => {
  assert.equal(aliasHost(website), "shop.example.com");
  assert.equal(aliasHost(""), "");
  assert.equal(aliasHost("not a url"), "");
  assert.equal(websitePrefix("shop.example.com"), "shop_example");
  assert.equal(websitePrefix("foo.bar.example.com"), "foo_bar_example");
  assert.equal(websitePrefix("127.0.0.1"), "127_0_0_1");
  assert.equal(websitePrefix("localhost"), "localhost");
});

test("alias: SimpleLogin puts the hostname in the query and the key in `Authentication`", () => {
  const req = aliasCreateRequest(settings({ vendor: "simplelogin", token: "tok" }), ctx);
  assert.equal(req.method, "POST");
  assert.equal(req.url, "https://app.simplelogin.io/api/alias/random/new?hostname=shop.example.com");
  assert.deepEqual(req.headers, { Accept: "application/json", "Content-Type": "application/json", Authentication: "tok" });
  assert.deepEqual(body(req), { note: "Website: https://shop.example.com/checkout?x=1. Generated by Plugwarden." });
  assert.equal(aliasResult(settings({ vendor: "simplelogin", token: "tok" }), { alias: "foo@example.com" }), "foo@example.com");
  // Self-hosted SimpleLogin.
  const selfHosted = aliasCreateRequest(settings({ vendor: "simplelogin", token: "tok", baseUrl: "https://sl.example.net" }), ctx);
  assert.equal(selfHosted.url, "https://sl.example.net/api/alias/random/new?hostname=shop.example.com");
});

test("alias: SimpleLogin without a website sends no hostname and the plain note", () => {
  const req = aliasCreateRequest(settings({ vendor: "simplelogin", token: "tok" }), { website: "", generatedBy });
  assert.equal(req.url, "https://app.simplelogin.io/api/alias/random/new");
  assert.deepEqual(body(req), { note: "Generated by Plugwarden." });
});

test("alias: Addy.io needs a domain and describes the host", () => {
  const s = settings({ vendor: "addyio", token: "tok", domain: "example.com" });
  const req = aliasCreateRequest(s, ctx);
  assert.equal(req.url, "https://app.addy.io/api/v1/aliases");
  assert.equal(req.headers.Authorization, "Bearer tok");
  assert.deepEqual(body(req), { domain: "example.com", description: "Website: shop.example.com. Generated by Plugwarden." });
  assert.equal(aliasResult(s, { data: { email: "foo@example.com" } }), "foo@example.com");
  assert.throws(() => aliasCreateRequest(settings({ vendor: "addyio", token: "tok" }), ctx), { code: "noDomain" });
});

test("alias: DuckDuckGo has no body and returns an @duck.com address", () => {
  const s = settings({ vendor: "duckduckgo", token: "tok" });
  const req = aliasCreateRequest(s, ctx);
  assert.equal(req.url, "https://quack.duckduckgo.com/api/email/addresses");
  assert.equal(req.headers.Authorization, "Bearer tok");
  assert.equal(req.body, undefined);
  assert.equal(aliasResult(s, { address: "foo" }), "foo@duck.com");
});

test("alias: Fastmail looks up the account, then creates a masked email", () => {
  const s = settings({ vendor: "fastmail", token: "tok" });
  const account = aliasAccountRequest(s);
  assert.ok(account);
  assert.equal(account.method, "GET");
  assert.equal(account.url, "https://api.fastmail.com/jmap/session");
  assert.equal(account.headers.Authorization, "Bearer tok");
  assert.equal(aliasAccountId({ primaryAccounts: { "https://www.fastmail.com/dev/maskedemail": "u1" } }), "u1");
  assert.throws(() => aliasAccountId({ primaryAccounts: {} }), { code: "noAccount" });

  const create = aliasCreateRequest(s, ctx, "u1");
  assert.equal(create.url, "https://api.fastmail.com/jmap/api/");
  const json = body(create);
  assert.deepEqual(json.using, ["https://www.fastmail.com/dev/maskedemail", "urn:ietf:params:jmap:core"]);
  const call = (json.methodCalls as unknown[][])[0] as [string, Record<string, unknown>];
  assert.equal(call[0], "MaskedEmail/set");
  assert.equal(call[1].accountId, "u1");
  assert.deepEqual((call[1].create as Record<string, Record<string, unknown>>)["new-masked-email"], {
    state: "enabled",
    description: "",
    forDomain: website,
    emailPrefix: "",
  });

  const prefixed = aliasCreateRequest(settings({ vendor: "fastmail", token: "tok", prefix: true }), ctx, "u1");
  const prefixedCall = (body(prefixed).methodCalls as unknown[][])[0] as [string, Record<string, unknown>];
  assert.equal((prefixedCall[1].create as Record<string, Record<string, unknown>>)["new-masked-email"].emailPrefix, "shop_example");

  const ok = { methodResponses: [["MaskedEmail/set", { created: { "new-masked-email": { email: "foo@fastmail.com" } } }, "0"]] };
  assert.equal(aliasResult(s, ok), "foo@fastmail.com");
  const denied = { methodResponses: [["MaskedEmail/set", { notCreated: { "new-masked-email": { description: "Quota exceeded" } } }, "0"]] };
  assert.throws(() => aliasResult(s, denied), /Quota exceeded/);
  const failed = { methodResponses: [["error", { description: "Forbidden" }, "0"]] };
  assert.throws(() => aliasResult(s, failed), /Forbidden/);
});

test("alias: Firefox Relay caps the description and stores the full URL", () => {
  const s = settings({ vendor: "firefox", token: "tok" });
  const req = aliasCreateRequest(s, ctx);
  assert.equal(req.url, "https://relay.firefox.com/api/v1/relayaddresses/");
  assert.equal(req.headers.Authorization, "Token tok");
  assert.deepEqual(body(req), {
    enabled: true,
    generated_for: website,
    description: "Website: shop.example.com. Generated by Plugwarden.",
  });
  const long = aliasCreateRequest(s, { website: `https://${"a".repeat(300)}.com`, generatedBy: () => "x".repeat(100) });
  const longBody = body(long);
  assert.equal((longBody.generated_for as string).length, 255);
  assert.equal((longBody.description as string).length, 64);
  assert.equal(aliasResult(s, { full_address: "foo@relay.firefox.com" }), "foo@relay.firefox.com");
});

test("alias: Forward Email uses basic auth and a per-domain path", () => {
  const s = settings({ vendor: "forwardemail", token: "tok", domain: "example.com" });
  const req = aliasCreateRequest(s, ctx);
  assert.equal(req.url, "https://api.forwardemail.net/v1/domains/example.com/aliases");
  assert.equal(req.headers.Authorization, `Basic ${btoa("tok:")}`);
  assert.deepEqual(body(req), { labels: website, description: "Website: https://shop.example.com/checkout?x=1. Generated by Plugwarden." });
  assert.equal(aliasResult(s, { name: "foo", domain: { name: "mail.example.com" } }), "foo@mail.example.com");
  // No domain in the response: fall back to the configured one.
  assert.equal(aliasResult(s, { name: "foo" }), "foo@example.com");
  // A missing token never leaves the extension.
  assert.throws(() => aliasCreateRequest(settings({ vendor: "forwardemail", domain: "example.com" }), ctx), { code: "noToken" });
});

test("alias: a response without an address is an error, not an empty alias", () => {
  assert.throws(() => aliasResult(settings({ vendor: "simplelogin", token: "t" }), { alias: "  " }), { code: "badResponse" });
  assert.throws(() => aliasResult(settings({ vendor: "addyio", token: "t", domain: "e.com" }), null), { code: "badResponse" });
  assert.throws(() => aliasResult(settings({ vendor: "duckduckgo", token: "t" }), {}), { code: "badResponse" });
  assert.throws(() => aliasResult(settings({ vendor: "firefox", token: "t" }), {}), { code: "badResponse" });
  assert.throws(() => aliasResult(settings({ vendor: "fastmail", token: "t" }), { methodResponses: [] }), { code: "badResponse" });
});

test("alias: every service has the settings the UI needs", () => {
  for (const [vendor, info] of Object.entries(ALIAS_INFO)) {
    assert.ok(info.fields.includes("token"), `${vendor} takes a token`);
    assert.ok(info.required.length > 0, `${vendor} has required fields`);
    for (const field of info.required) assert.ok(info.fields.includes(field), `${vendor}: ${field} is displayed`);
    assert.ok(info.baseUrl.startsWith("https://"), `${vendor} defaults to https`);
  }
});

test("alias: the generated-by note is passed through, never re-parsed", () => {
  const withWebsite = (target: string) => `Website: ${target}. Generated by Plugwarden.`;
  // Addy.io and Firefox Relay pass a bare host; re-parsing it would produce "Website: ." (see the
  // service worker's error mapping).
  assert.equal(aliasGeneratedBy("shop.example.com", "plain", withWebsite), "Website: shop.example.com. Generated by Plugwarden.");
  // SimpleLogin and Forward Email pass the full page URL.
  assert.equal(aliasGeneratedBy(website, "plain", withWebsite), `Website: ${website}. Generated by Plugwarden.`);
  assert.equal(aliasGeneratedBy("", "plain", withWebsite), "plain");
});
